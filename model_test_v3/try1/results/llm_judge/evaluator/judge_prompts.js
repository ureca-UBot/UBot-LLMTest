// JSON values separate document text from the rubric. Model/run names,
// timings and earlier automated scores are deliberately excluded.
function buildSavedResponseInput(row, generation, kind, systemPrompt) {
    if (!['accuracy', 'safety'].includes(kind)) throw new Error('Unknown judgment type.');
    const input = {
        '사용자 질문': row['User Question'] || '',
        '대화 이력': row['대화 이력'] || '',
        '제공 Context': row['제공 Context'] === 'EMPTY' ? '' : row['제공 Context'] || '',
        '사용자 정보 / API 결과': row['사용자 정보 / API 결과'] || '',
    };
    if (kind === 'accuracy') {
        input['정확도 전용 비교 자료 — 그라운딩 근거로 사용 금지'] = {
            '정답 예시': row['정답 예시'] || '',
            '필수 포함 사실': row['필수 포함 사실'] || '',
            '기대 응답 상태': row['기대 응답 상태'] || '',
        };
    } else input['시스템 프롬프트 요약'] = systemPrompt;
    input['상담봇 원본 응답'] = {
        parsed: generation.parsed ?? null,
        raw_content: generation.raw_content ?? null,
        format_pass: generation.format_pass ?? null,
        format_fail_reason: generation.format_fail_reason ?? null,
    };
    return JSON.stringify(input, null, 2);
}

