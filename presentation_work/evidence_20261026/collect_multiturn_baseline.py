"""Read-only evidence audit: saved original-query retrieval and history A/D trials."""
from pathlib import Path
from collections import Counter
import json,hashlib,math

ROOT=Path(r'C:\Ureka\ureca_project2\LLM_Test')
OUT=ROOT/'presentation_work/evidence_20261026'
P=ROOT.parent/'eval_205_multiturn/docs-evaluation/2026-10-15-keep-search'
sources=[]
def read(name):
    p=Path(name);p=p if p.is_absolute() else P/p
    b=p.read_bytes();sources.append(dict(path=str(p),sha256=hashlib.sha256(b).hexdigest()))
    return json.loads(b.decode('utf-8-sig'))
def lines(name):
    p=P/name;b=p.read_bytes();sources.append(dict(path=str(p),sha256=hashlib.sha256(b).hexdigest()))
    return [json.loads(s) for s in b.decode('utf-8-sig').splitlines() if s.strip()]
cases={c['id']:c for c in read(P.parent/'2026-10-15-guard/reviewed-results.json')['cases']}
gold={k:v for k,v in read('gold.json').items() if not k.startswith('_')}
original=read('scores-orig-full.json');rewritten=read('built4.json')
def grade(g,tops):
    ids={fid for top in tops for fid,s in top[:3] if s>=.75}
    if not g:return 'NO_GOLD_BUT_PASSED' if ids else 'NO_GOLD_NO_PASS'
    n=sum(bool(ids&set(intent)) for intent in g)
    return 'ALL_HIT' if n==len(g) else 'PARTIAL_HIT' if n else 'WRONG_PASSED' if ids else 'NO_PASS'
detail=[]
for cid in gold:
    c=cases[cid]
    detail.append(dict(id=cid,question=c['question'],expected=c.get('expected'),has_history=bool(c.get('history')),
      gold=gold[cid],original_tops=original[c['question']],search_queries=rewritten[cid]['search'],search_tops=rewritten[cid]['searchTop'],
      original=grade(gold[cid],[original[c['question']]]),search=grade(gold[cid],rewritten[cid]['searchTop'])))
groups={}
for name,rows in [
    ('history_all_59',[r for r in detail if r['has_history']]),
    ('history_positive_41',[r for r in detail if r['has_history'] and r['gold']]),
    ('history_no_gold_18',[r for r in detail if r['has_history'] and not r['gold']])]:
    gain=[r['id'] for r in rows if r['original']!='ALL_HIT' and r['search']=='ALL_HIT']
    loss=[r['id'] for r in rows if r['original']=='ALL_HIT' and r['search']!='ALL_HIT']
    n=len(gain)+len(loss)
    p=min(1.,2*sum(math.comb(n,i) for i in range(min(len(gain),len(loss))+1))/2**n) if n else 1.
    groups[name]=dict(n=len(rows),original=dict(Counter(r['original'] for r in rows)),search=dict(Counter(r['search'] for r in rows)),gain_ids=gain,loss_ids=loss,all_hit_mcnemar_p=p)
answer_trials={}
for name in ['answer-eval.jsonl','answer-eval-plain-D.jsonl']:
    a=lines(name)
    before={r['id']:r for r in a if r['condition']=='A' and not r['inject']}
    after={r['id']:r for r in a if r['condition']=='D' and not r['inject']}
    ids=sorted(set(before)&set(after))
    assert all(before[i]['question']==after[i]['question'] and before[i]['subs']==after[i]['subs'] for i in ids)
    answer_trials[name]=dict(n=len(ids),ids=ids,conditions=dict(Counter(r['condition'] for r in a)),
      pairs=[dict(id=i,before=before[i],after=after[i]) for i in ids],
      scope='A omits history from answer LLM; D adds user/assistant turns. Identical rewritten search queries and FAQ IDs in each pair. Retrieval already uses history-based rewritten queries. No saved paired accuracy/hallucination Judge found for these 19 pairs.')
result=dict(retrieval_groups=groups,retrieval_rows=detail,answer_trials=answer_trials,
  conclusion='Saved same-question comparisons exist for retrieval context rewriting and answer-history input. They do not constitute a controlled final end-to-end multiturn ON/OFF evaluation.',
  limitations=['2026-10-15 exploratory keep/search design, later replaced by search-only/code-original design.',
  'Gold FAQ labels generated by Claude, not human-verified; selected diagnostic/adversarial cases, not a random production sample.',
  'Original-query retrieval is a saved vector-search baseline, not a recorded run of the full old API.',
  'BGE-M3 top3 with rounded cosine score >=0.75. ALL_HIT requires every annotated intent to have a matching gold FAQ.',
  'A/D has 19 matched non-injected cases in each format variant; they reuse the same IDs and must not be summed as 38 unique questions.',
  'No new embeddings, LLM responses or Judge calls were made.'])
(OUT/'multiturn_before_after.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
(OUT/'multiturn_before_after_sources.json').write_text(json.dumps(sources,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps(groups,ensure_ascii=False,indent=2))
print('ANSWER A/D',[(k,v['n']) for k,v in answer_trials.items()])
print('GAIN EXAMPLES')
for r in detail:
    if r['id'] in groups['history_positive_41']['gain_ids']:
        print(r['id'],r['question'],'->',r['search_queries'],'gold',r['gold'])
