'use strict';
// 380문항 파일부터 도입된 반복테스트 구조: 40개 문항은 실행 회차 1/2/3으로
// 3번(ID: `SF-0001`/`SF-0001-R2`/`SF-0001-R3`, 전부 같은 `원본 ID`), 나머지
// 260개는 회차 1만 있음. "정답률/포맷성공률/유사도 통과율" 같은 집계 지표는
// 회차 1(=고유 300문항)만 기준으로 계산한다 — 안 그러면 반복 대상으로 뽑힌
// 40문항이 우연히 3배 더 크게 집계에 반영되어 편향이 생김(원본 xlsx "요약"
// 시트의 "정확도는 회차 1인 300문항으로 집계" 원칙 그대로).
//
// 건별 상세(jsonl)는 여전히 380행 전부 기록한다 — 집계에서만 회차1로
// 좁히고, 개별 조회는 그대로 다 보이게.

function isPrimaryRound(caseRow) {
  return caseRow['실행 회차'] === '1' || !caseRow['실행 회차'];
}

module.exports = { isPrimaryRound };
